export function applyDepth(lectures) {
  for (const lecture of lectures) {
    const extra = DEPTH[lecture.id];
    if (!extra) continue;
    lecture.beats.push(extra.beat);
    if (Array.isArray(lecture.outcomes)) lecture.outcomes.push(extra.outcome);
    if (Array.isArray(lecture.quiz) && lecture.quiz.length >= 3) lecture.quiz[2] = extra.quiz;
  }
}

