/** One deeper beat per lecture, drawn on the whiteboard and checked in the quiz. */

const B = (x, y, w, h, label, pen) => ({ t: "box", x, y, w, h, label, pen });
const A = (x1, y1, x2, y2, pen) => ({ t: "arrow", x1, y1, x2, y2, pen });
const T = (x, y, label, pen, anchor) => ({ t: "text", x, y, label, pen, anchor });
const L = (x1, y1, x2, y2, pen) => ({ t: "line", x1, y1, x2, y2, pen });
const C = (x, y, r, label, pen) => ({ t: "circ", x, y, r, label, pen });
const D = (x, y, pen) => ({ t: "dot", x, y, r: 5, pen });
const P = (d, pen) => ({ t: "path", d, pen });

function lesson(title, say, sayUr, ink, note, outcome, quiz) {
  return {
    outcome,
    beat: { title, say, sayUr, scene: { type: "whiteboard", title, ink, note } },
    quiz,
  };
}

function ask(q, choices, answer, why) {
  return { q, choices, answer, why };
}

