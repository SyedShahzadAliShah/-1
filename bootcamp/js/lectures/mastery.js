export function applyMastery(lectures) {
  for (const lecture of lectures) {
    const extra = MASTERY[lecture.id];
    if (!extra) continue;
    lecture.beats.forEach((item) => {
      if (!item.role) item.role = item.scene?.type === "whiteboard" ? "depth" : "idea";
    });
    lecture.beats.push(extra.worked, extra.trap, extra.recap);
    lecture.sheet = extra.sheet;
    lecture.drill = extra.drill;
    extra.quizTraps.forEach((text, index) => {
      if (lecture.quiz[index]) lecture.quiz[index].trap = text;
    });
    if (Array.isArray(lecture.outcomes)) {
      lecture.outcomes.push("Work a short example and name the exam trap.");
    }
  }
}

export const masteryIds = Object.keys(MASTERY);
