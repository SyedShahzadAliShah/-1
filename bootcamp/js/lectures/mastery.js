export const ROLE_LABEL = {
  idea: "Idea",
  depth: "Deeper rule",
  example: "Worked example",
  trap: "Watch the trap",
  recap: "Exam sheet",
};

export const ROLE_ORDER = ["idea", "depth", "example", "trap", "recap"];

function beat(title, say, sayUr, scene, role) {
  return { title, say, sayUr, scene, role };
}

function pack({
  exampleTitle, exampleSay, exampleSayUr, problem, steps, exampleNote,
  trapTitle, trapSay, trapSayUr, wrong, right, fix,
  recapTitle, recapSay, recapSayUr, lines, formula, sayThis,
  drillQ, drillReveal, quizTraps,
}) {
  return {
    worked: beat(exampleTitle, exampleSay, exampleSayUr, {
      type: "steps", title: exampleTitle, problem, steps, note: exampleNote,
    }, "example"),
    trap: beat(trapTitle, trapSay, trapSayUr, {
      type: "trap", title: trapTitle, wrong, right, note: fix,
    }, "trap"),
    recap: beat(recapTitle, recapSay, recapSayUr, {
      type: "sheet", title: recapTitle, lines, formula, sayThis,
    }, "recap"),
    sheet: { lines, formula, sayThis },
    drill: { q: drillQ, reveal: drillReveal },
    quizTraps,
  };
}

